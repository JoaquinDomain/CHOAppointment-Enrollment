-- ----------------------------------------------------------------------------
-- 0. Safety check: confirm the database does not already exist and does not
--    belong to another application. Review the result before continuing.
-- ----------------------------------------------------------------------------
SELECT SCHEMA_NAME
  FROM information_schema.SCHEMATA
 WHERE SCHEMA_NAME = '<APP_DB_NAME>';

-- ----------------------------------------------------------------------------
-- 1. Create the dedicated database.
--    utf8mb4_0900_ai_ci is required by the schema and the application checks.
-- ----------------------------------------------------------------------------
CREATE DATABASE `<APP_DB_NAME>`
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_0900_ai_ci;

-- ----------------------------------------------------------------------------
-- 2. Create the application account.
--
--    MySQL matches the account by BOTH user name and host. Create the account
--    for the exact host the application connects from:
--
--      remote app server:  'cho_app'@'10.0.0.25'
--      same-host TCP:      'cho_app'@'127.0.0.1'
--      same-host socket:   'cho_app'@'localhost'
--
--    If MySQL runs with skip_name_resolve=ON, 'localhost' matches only the
--    Unix socket. A TCP connection to 127.0.0.1 then needs an account whose
--    host is '127.0.0.1'. Confirm the mode with MICT.
--
--    Avoid '%' unless MICT has a documented reason and a firewall restriction.
-- ----------------------------------------------------------------------------
CREATE USER '<APP_DB_USER>'@'<APP_HOST>'
  IDENTIFIED BY '<STRONG_PASSWORD>';

-- ----------------------------------------------------------------------------
-- 3. Runtime privileges.
--    The application needs only DML at runtime.
-- ----------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE
  ON `<APP_DB_NAME>`.*
  TO '<APP_DB_USER>'@'<APP_HOST>';

-- ----------------------------------------------------------------------------
-- 4. Migration privileges.
--
--    Grant these ONLY while the migration runner is applying schema changes.
--    If MICT applies migrations with a separate DBA account, skip this section
--    and keep the application account DML-only.
