-- ----------------------------------------------------------------------------
-- 5. After migrations, revoke schema-change privileges if the application
--    account must remain DML-only. Run this only after `npm run db:verify`
--    passes and MICT confirms no further migration will be applied by this
--    account.
-- ----------------------------------------------------------------------------
